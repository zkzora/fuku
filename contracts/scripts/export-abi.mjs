#!/usr/bin/env node
/**
 * Copies each contract ABI from Hardhat artifacts into abi/<Name>.json and generates
 * abi/index.ts with `as const` exports for viem / wagmi consumers.
 *
 *   npx hardhat compile && node scripts/export-abi.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactsDir = path.join(root, "artifacts", "contracts");
const abiDir = path.join(root, "abi");

// name -> source path under contracts/ (artifacts mirror it: artifacts/contracts/<source>/<name>.json)
const SOURCES = [
  ["HumanIdentityRegistry", "HumanIdentityRegistry.sol"],
  ["AgentRegistry", "AgentRegistry.sol"],
  ["PermissionRegistry", "PermissionRegistry.sol"],
  ["ReputationRegistry", "ReputationRegistry.sol"],
  ["CleanverseAPassSim", "sim/CleanverseAPassSim.sol"],
  ["CleanverseATokenSim", "sim/CleanverseATokenSim.sol"],
  ["FukuSpendGuard", "FukuSpendGuard.sol"],
];
const CONTRACTS = SOURCES.map(([name]) => name);

mkdirSync(abiDir, { recursive: true });

const exportsTs = [];
for (const [name, source] of SOURCES) {
  const artifactPath = path.join(artifactsDir, ...source.split("/"), `${name}.json`);
  if (!existsSync(artifactPath)) {
    console.error(`Missing artifact ${artifactPath}. Run "npx hardhat compile" first.`);
    process.exit(1);
  }
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  const abi = artifact.abi;

  writeFileSync(path.join(abiDir, `${name}.json`), JSON.stringify(abi, null, 2) + "\n");
  exportsTs.push(`export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;`);
  console.log(`abi/${name}.json  (${abi.length} entries)`);
}

const header = [
  "// AUTO-GENERATED by scripts/export-abi.mjs. Do not edit by hand.",
  "// Run: npx hardhat compile && node scripts/export-abi.mjs",
  "",
].join("\n");

const footer = [
  "",
  "export const FukuAbis = {",
  ...CONTRACTS.map((n) => `  ${n}: ${n}Abi,`),
  "} as const;",
  "",
  "export type FukuContractName = keyof typeof FukuAbis;",
  "",
].join("\n");

writeFileSync(path.join(abiDir, "index.ts"), header + exportsTs.join("\n\n") + "\n" + footer);
console.log("abi/index.ts");

// --- Web app copy ------------------------------------------------------------------------
// Same export names (HumanIdentityRegistryAbi, ...) that web/src/lib/chain/index.ts imports.
const webTarget =
  process.env.FUKU_WEB_ABI_PATH === "skip"
    ? null
    : path.resolve(root, process.env.FUKU_WEB_ABI_PATH ?? path.join("..", "web", "src", "lib", "chain", "abi.ts"));

if (webTarget) {
  if (!existsSync(path.dirname(webTarget))) {
    console.warn(`Skipping web ABI copy: ${path.dirname(webTarget)} does not exist`);
  } else {
    const webHeader = [
      "// AUTO-GENERATED by contracts/scripts/export-abi.mjs. Do not edit by hand.",
      "// Regenerate: cd contracts && npm run compile && npm run export-abi",
      "//",
      "// Full ABIs of the Fuku registries, FukuSpendGuard and the Cleanverse simulator contracts",
      "// (see /contracts). Kept inline so the web app builds",
      "// without the Hardhat artifacts; custom errors are included so viem can decode reverts.",
      "",
    ].join("\n");
    writeFileSync(webTarget, webHeader + exportsTs.join("\n\n") + "\n" + footer);
    console.log(path.relative(root, webTarget).split(path.sep).join("/"));
  }
}
